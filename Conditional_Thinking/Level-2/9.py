if day < 1 or day > 7:
    print("Invalid day !!!")

else:

    if day == 1:
        print("Monday")

    elif(day == 2):
        print("Tuesday")

    elif(day == 3):
        print("Tuesday")

    elif(day == 4):
        print("Tuesday")

    elif(day == 5):
        print("Tuesday")

    elif(day == 6):
        print("Tuesday")

    else:
          print("Sunday")

